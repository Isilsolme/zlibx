#!/usr/bin/env python3
"""Generate lib/l10n/s_keys.dart from the language tables.

Reads the five translation tables in lib/l10n/translations/
(en, ja, ko, zh, zh_hant), takes the union of their keys, and emits
one compile-time constant per key in `abstract final class S`:

    static const String recentSearches = 'recent_searches';

so call sites can write `l.get(S.recentSearches)` instead of a bare
string, turning a key typo from a silent runtime fallback into a
compile-time error.

Usage (from the repo root):

    python3 scripts/gen_l10n_keys.py

Paths are resolved relative to this file, so it also works from any
other working directory. The output is deterministic: keys are sorted
alphabetically by their snake_case form, the header is fixed, and no
timestamps are emitted.

The five tables must contain exactly the same key set. If they differ
(or a table is missing, a key is duplicated, or a key cannot be
converted cleanly to a valid Dart identifier) the script exits
non-zero and prints what is wrong instead of writing a bad file.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

# Language tables, relative to the repo root (lib/l10n/translations/).
LANG_FILES = ("en", "ja", "ko", "zh", "zh_hant")

# Keys only — values are deliberately NOT parsed: a value may be
# double-quoted (e.g. "Don't have an account? ") or span several
# lines, so a key:value pattern would silently miss entries. Every
# key entry starts its own line: `  'some_key': ...`.
KEY_RE = re.compile(r"""^\s*'([A-Za-z0-9_]+)'\s*:""", re.MULTILINE)

# A well-formed key: lower_snake_case, no leading/trailing/double
# underscores, each word starting with a lowercase letter or digit.
SNAKE_RE = re.compile(r"[a-z][a-z0-9]*(_[a-z0-9]+)*\Z")

# A well-formed generated identifier: lowerCamelCase.
IDENT_RE = re.compile(r"[a-z][A-Za-z0-9]*\Z")

# Dart reserved words that may not be used as identifiers.
DART_RESERVED = frozenset(
    """
    abstract as assert async await break case catch class const
    continue covariant default deferred do dynamic else enum export
    extends extension external factory false final finally for
    Function get hide if implements import in interface is late
    library mixin new null of on operator part required rethrow
    return set show static super switch sync this throw true try
    type typedef var void while with yield
    """.split()
)

# Header of the generated file, reproduced verbatim. Note that
# `S.recentSearches` in the comment is aspirational: there is no
# `recent_searches` key in the tables (yet). The header is kept
# exactly as the checked-in file has it; do not "fix" it here.
HEADER = (
    "// GENERATED by scripts/gen_l10n_keys.py — do not edit by hand.\n"
    "//\n"
    "// 编译期键常量表：`l.get(S.recentSearches)` 代替裸字符串\n"
    "// `l.get('recent_searches')`——键名 typo 从运行时静默回退\n"
    "// （显示英文或键名本身）变成编译期错误。键集来自 5 个语言\n"
    "// 表的并集；重新生成：`python3 scripts/gen_l10n_keys.py`。\n"
)


def fail(message: str) -> "NoReturn":
    """Print an error to stderr and exit non-zero (never returns)."""
    print(f"gen_l10n_keys: error: {message}", file=sys.stderr)
    raise SystemExit(1)


def parse_table(path: Path) -> set[str]:
    """Return the set of keys defined in one translation table."""
    if not path.is_file():
        fail(f"missing translation table: {path}")
    text = path.read_text(encoding="utf-8")
    keys = KEY_RE.findall(text)
    duplicates = sorted({k for k in keys if keys.count(k) > 1})
    if duplicates:
        fail(f"{path}: duplicate key(s): {', '.join(duplicates)}")
    return set(keys)


def to_camel_case(snake: str) -> str:
    """Convert a snake_case key to a lowerCamelCase Dart identifier."""
    words = snake.split("_")
    return words[0] + "".join(word.capitalize() for word in words[1:])


def check_key(snake: str) -> str:
    """Validate one key and return its camelCase identifier.

    Raises SystemExit (non-zero, with an explicit message) instead of
    silently mangling a key that does not convert cleanly.
    """
    if not SNAKE_RE.fullmatch(snake):
        fail(
            f"key {snake!r} is not lower_snake_case "
            "(expected e.g. 'recent_searches'); refusing to guess "
            "a Dart identifier for it"
        )
    camel = to_camel_case(snake)
    if not IDENT_RE.fullmatch(camel):
        fail(
            f"key {snake!r} converts to {camel!r}, which is not a "
            "valid Dart identifier"
        )
    if camel in DART_RESERVED:
        fail(
            f"key {snake!r} converts to {camel!r}, which is a Dart "
            "reserved word and cannot be used as an identifier"
        )
    return camel


def main() -> int:
    root = Path(__file__).resolve().parent.parent
    translations_dir = root / "lib" / "l10n" / "translations"
    output_path = root / "lib" / "l10n" / "s_keys.dart"

    # 1. Parse all five tables.
    key_sets = {
        lang: parse_table(translations_dir / f"{lang}.dart")
        for lang in LANG_FILES
    }

    # 2. The five key sets must be identical; fail loudly if not.
    reference = key_sets[LANG_FILES[0]]
    mismatched = False
    for lang in LANG_FILES[1:]:
        keys = key_sets[lang]
        if keys != reference:
            mismatched = True
            missing = sorted(reference - keys)
            extra = sorted(keys - reference)
            print(
                f"gen_l10n_keys: error: {lang}.dart key set differs "
                f"from {LANG_FILES[0]}.dart:",
                file=sys.stderr,
            )
            if missing:
                print(
                    f"  missing ({len(missing)}): "
                    + ", ".join(missing),
                    file=sys.stderr,
                )
            if extra:
                print(
                    f"  extra ({len(extra)}): " + ", ".join(extra),
                    file=sys.stderr,
                )
    if mismatched:
        print(
            "gen_l10n_keys: error: refusing to generate s_keys.dart "
            "until all five tables agree on the same key set.",
            file=sys.stderr,
        )
        return 1

    # 3. Union of keys (== the common set, verified above), sorted
    # alphabetically by snake_case key; validate every conversion
    # and reject camelCase collisions (two keys, one identifier).
    keys = sorted(set().union(*key_sets.values()))
    camel_by_snake: dict[str, str] = {}
    seen_camel: dict[str, str] = {}
    for snake in keys:
        camel = check_key(snake)
        if camel in seen_camel and seen_camel[camel] != snake:
            fail(
                f"keys {seen_camel[camel]!r} and {snake!r} both "
                f"convert to {camel!r}; refusing to emit a "
                "colliding identifier"
            )
        seen_camel[camel] = snake
        camel_by_snake[snake] = camel

    # 4. Emit the file: verbatim header, class opener, one line per
    # key, class closer. Single trailing newline, LF only.
    lines = [HEADER.rstrip("\n"), "abstract final class S {"]
    lines += [
        f"  static const String {camel_by_snake[snake]} = '{snake}';"
        for snake in keys
    ]
    lines.append("}")
    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"gen_l10n_keys: wrote {output_path} ({len(keys)} keys)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
