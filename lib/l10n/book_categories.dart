/// One parsed category from the eapi `categories` value.
typedef ParsedBookCategory = ({int? id, String name});

/// Parse the eapi `categories` value into individual categories.
///
/// The wire format is `{307: History - World history, 14: Fiction}`; a
/// plain name without braces or id (`Fiction - Horror`) parses as one entry
/// with a null id. Names may contain commas (e.g.
/// `Crime, Thrillers & Mystery`), so entries are split on the next
/// `<digits>:` marker, never on commas.
/// NOTE: keep each backticked span on a single line — the
/// `unintended_html_in_doc_comment` lint scans lines independently, so a
/// code span split across lines leaves the `<digits>:` below unprotected.
List<ParsedBookCategory> parseBookCategories(String? raw) {
  final text = raw?.trim();
  if (text == null || text.isEmpty) return const [];
  final body = text.startsWith('{') && text.endsWith('}')
      ? text.substring(1, text.length - 1)
      : text;
  final idPattern = RegExp(r'(\d+)\s*:\s*');
  final matches = idPattern.allMatches(body).toList();
  if (matches.isEmpty) {
    final name = body.trim();
    return name.isEmpty ? const [] : [(id: null, name: name)];
  }
  final out = <ParsedBookCategory>[];
  for (var i = 0; i < matches.length; i++) {
    final start = matches[i].end;
    final end = i + 1 < matches.length ? matches[i + 1].start : body.length;
    var name = body.substring(start, end).trim();
    if (name.endsWith(',')) name = name.substring(0, name.length - 1).trim();
    if (name.isEmpty) continue;
    out.add((id: int.parse(matches[i].group(1)!), name: name));
  }
  return out;
}

/// Localize one parsed category for [locale]: zh / zh_Hant use the table
/// above; every other locale (and any id missing from the table) shows the
/// English name the API returned. When the name repeats the parent word
/// ("Psychology - Psychology - theory, history & research"), the parent
/// part is dropped so the chip does not show the word twice.
String localizedBookCategoryName(ParsedBookCategory category, Locale locale) {
  final entry =
      category.id == null ? null : kBookCategoryNames[category.id];
  final String name;
  if (entry == null) {
    name = category.name;
  } else if (locale.languageCode == 'zh') {
    // Same zh / zh_Hant split as _lookupKey in app_localizations.dart.
    if (locale.scriptCode == 'Hant') {
      name = entry.zhHant;
    } else {
      final country = locale.countryCode;
      name = (country == 'TW' || country == 'HK' || country == 'MO')
          ? entry.zhHant
          : entry.zh;
    }
  } else {
    name = category.name;
  }
  return _dedupeParent(name);
}

/// Drop a doubled parent word: for "A - A..." (the child part already
/// starts with the parent name) show the child part alone.
String _dedupeParent(String name) {
  final dash = name.indexOf(' - ');
  if (dash <= 0) return name;
  final parent = name.substring(0, dash);
  final child = name.substring(dash + 3);
  if (child.startsWith(parent)) return child;
  return name;
}
